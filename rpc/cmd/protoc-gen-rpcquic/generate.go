package main

import (
	"fmt"
	"path"
	"strings"

	"google.golang.org/protobuf/compiler/protogen"
	"google.golang.org/protobuf/reflect/protoreflect"
	"google.golang.org/protobuf/types/descriptorpb"
)

const (
	contextPackage = protogen.GoImportPath("context")
	rpcPackage     = protogen.GoImportPath("github.com/VladimirKhmelev/quic-rpc-go/rpc")
	codesPackage   = protogen.GoImportPath("github.com/VladimirKhmelev/quic-rpc-go/rpc/codes")
	statusPackage  = protogen.GoImportPath("github.com/VladimirKhmelev/quic-rpc-go/rpc/status")
)

// Field numbers in FileDescriptorProto whose comments go to the file header.
const (
	filePackageField = 2
	fileSyntaxField  = 12
)

const deprecationComment = "// Deprecated: Do not use."

// generateFile writes the clients and servers of the services of file.
func generateFile(gen *protogen.Plugin, file *protogen.File, suffix string) error {
	if len(file.Services) == 0 {
		return nil
	}
	for _, s := range file.Services {
		for _, m := range s.Methods {
			if k := streamingKind(m); k != "" {
				return fmt.Errorf("%s: %s is a %s method; protoc-gen-rpcquic supports only unary and bidirectional streaming methods for now",
					file.Desc.Path(), m.Desc.FullName(), k)
			}
		}
	}

	packageName, importPath, filename := output(file, suffix)
	g := gen.NewGeneratedFile(filename, importPath)
	genLeadingComments(g, file.Desc.SourceLocations().ByPath(protoreflect.SourcePath{fileSyntaxField}))
	g.P("// Code generated by protoc-gen-rpcquic. DO NOT EDIT.")
	g.P("// versions:")
	g.P("// - protoc-gen-rpcquic ", version)
	g.P("// - protoc             ", protocVersion(gen))
	if file.Proto.GetOptions().GetDeprecated() {
		g.P("// ", file.Desc.Path(), " is a deprecated file.")
	} else {
		g.P("// source: ", file.Desc.Path())
	}
	g.P()
	genLeadingComments(g, file.Desc.SourceLocations().ByPath(protoreflect.SourcePath{filePackageField}))
	g.P("package ", packageName)
	g.P()
	g.P("// This is a compile-time assertion that this generated file is compatible")
	g.P("// with the rpc package it is compiled against.")
	g.P("const _ = ", rpcPackage.Ident("SupportPackageIsVersion1"))
	g.P()
	for _, s := range file.Services {
		genService(g, file, s)
	}
	return nil
}

// streamingKind names the kind of a method this generator does not support
// yet, or returns "" for unary and bidirectional methods.
func streamingKind(m *protogen.Method) string {
	switch {
	case m.Desc.IsStreamingServer() && !m.Desc.IsStreamingClient():
		return "server-streaming"
	case m.Desc.IsStreamingClient() && !m.Desc.IsStreamingServer():
		return "client-streaming"
	default:
		return ""
	}
}

// output returns the package, import path and file name of the generated
// code: the sub-package <package><suffix> next to the messages, as
// protoc-gen-connect-go does, or the package of the messages for "".
func output(file *protogen.File, suffix string) (protogen.GoPackageName, protogen.GoImportPath, string) {
	prefix := file.GeneratedFilenamePrefix
	if suffix == "" {
		return file.GoPackageName, file.GoImportPath, prefix + ".rpcquic.go"
	}
	name := protogen.GoPackageName(string(file.GoPackageName) + suffix)
	importPath := protogen.GoImportPath(path.Join(string(file.GoImportPath), string(name)))
	return name, importPath, path.Join(path.Dir(prefix), string(name), path.Base(prefix)) + ".rpcquic.go"
}

func protocVersion(gen *protogen.Plugin) string {
	v := gen.Request.GetCompilerVersion()
	if v == nil {
		return "(unknown)"
	}
	var suffix string
	if s := v.GetSuffix(); s != "" {
		suffix = "-" + s
	}
	return fmt.Sprintf("v%d.%d.%d%s", v.GetMajor(), v.GetMinor(), v.GetPatch(), suffix)
}

func genService(g *protogen.GeneratedFile, file *protogen.File, s *protogen.Service) {
	clientName := s.GoName + "Client"
	serverName := s.GoName + "Server"
	descVar := s.GoName + "_ServiceDesc"
	deprecated := s.Desc.Options().(*descriptorpb.ServiceOptions).GetDeprecated()

	g.P("// Full names of the methods of the ", s.GoName, " service.")
	g.P("const (")
	for _, m := range s.Methods {
		g.P(fullMethodName(s, m), ` = "/`, s.Desc.FullName(), "/", m.Desc.Name(), `"`)
	}
	g.P(")")
	g.P()

	// Client.
	g.P("// ", clientName, " is the client API for the ", s.GoName, " service.")
	genServiceComments(g, s, deprecated)
	g.P("type ", clientName, " interface {")
	for _, m := range s.Methods {
		genMethodComments(g, m)
		g.P(clientSignature(g, m))
	}
	g.P("}")
	g.P()
	g.P("type ", unexport(clientName), " struct {")
	g.P("cc ", rpcPackage.Ident("ClientConnInterface"))
	g.P("}")
	g.P()
	g.P("// New", clientName, " returns a client of the ", s.GoName, " service that calls cc.")
	if deprecated {
		g.P("//")
		g.P(deprecationComment)
	}
	g.P("func New", clientName, "(cc ", rpcPackage.Ident("ClientConnInterface"), ") ", clientName, " {")
	g.P("return &", unexport(clientName), "{cc}")
	g.P("}")
	g.P()
	streamIndex := 0
	for _, m := range s.Methods {
		genClientMethod(g, s, m, streamIndex)
		if m.Desc.IsStreamingClient() {
			streamIndex++
		}
	}

	// Server.
	g.P("// ", serverName, " is the server API for the ", s.GoName, " service.")
	g.P("// Implementations must embed Unimplemented", serverName, " for forward compatibility.")
	genServiceComments(g, s, deprecated)
	g.P("type ", serverName, " interface {")
	for _, m := range s.Methods {
		genMethodComments(g, m)
		g.P(serverSignature(g, m))
	}
	g.P("mustEmbedUnimplemented", serverName, "()")
	g.P("}")
	g.P()

	g.P("// Unimplemented", serverName, " answers every method with codes.Unimplemented.")
	g.P("// Embed it by value, not by pointer: a nil pointer would panic on the")
	g.P("// first call of a method that is not implemented.")
	g.P("type Unimplemented", serverName, " struct{}")
	g.P()
	for _, m := range s.Methods {
		g.P("func (Unimplemented", serverName, ") ", serverSignature(g, m), " {")
		if isUnary(m) {
			g.P("return nil, ", statusPackage.Ident("Error"), "(", codesPackage.Ident("Unimplemented"), `, "method `, m.GoName, ` not implemented")`)
		} else {
			g.P("return ", statusPackage.Ident("Error"), "(", codesPackage.Ident("Unimplemented"), `, "method `, m.GoName, ` not implemented")`)
		}
		g.P("}")
	}
	g.P("func (Unimplemented", serverName, ") mustEmbedUnimplemented", serverName, "() {}")
	g.P("func (Unimplemented", serverName, ") testEmbeddedByValue() {}")
	g.P()

	g.P("// Unsafe", serverName, " may be embedded instead of Unimplemented", serverName)
	g.P("// to opt out of forward compatibility: methods added to ", serverName)
	g.P("// later then break the build. Its use is not recommended.")
	g.P("type Unsafe", serverName, " interface {")
	g.P("mustEmbedUnimplemented", serverName, "()")
	g.P("}")
	g.P()

	g.P("// Register", serverName, " registers srv as the ", s.GoName, " service on s.")
	if deprecated {
		g.P("//")
		g.P(deprecationComment)
	}
	g.P("func Register", serverName, "(s ", rpcPackage.Ident("ServiceRegistrar"), ", srv ", serverName, ") {")
	g.P("// Panics now if Unimplemented", serverName, " was embedded by a nil pointer,")
	g.P("// rather than on the first call of an unimplemented method.")
	g.P("if t, ok := srv.(interface{ testEmbeddedByValue() }); ok {")
	g.P("t.testEmbeddedByValue()")
	g.P("}")
	g.P("s.RegisterService(&", descVar, ", srv)")
	g.P("}")
	g.P()

	var methods, streams []string
	for _, m := range s.Methods {
		if isUnary(m) {
			genUnaryHandler(g, s, m)
			methods = append(methods, m.GoName)
		} else {
			genBidiHandler(g, s, m)
			streams = append(streams, m.GoName)
		}
	}

	g.P("// ", descVar, " describes the ", s.GoName, " service for rpc.Server.RegisterService.")
	g.P("// Use Register", serverName, " rather than this variable.")
	g.P("var ", descVar, " = ", rpcPackage.Ident("ServiceDesc"), "{")
	g.P(`ServiceName: "`, s.Desc.FullName(), `",`)
	g.P("HandlerType: (*", serverName, ")(nil),")
	g.P("Methods: []", rpcPackage.Ident("MethodDesc"), "{")
	for _, name := range methods {
		g.P("{")
		g.P(`MethodName: "`, name, `",`)
		g.P("Handler: ", handlerName(s, name), ",")
		g.P("},")
	}
	g.P("},")
	g.P("Streams: []", rpcPackage.Ident("StreamDesc"), "{")
	for _, name := range streams {
		g.P("{")
		g.P(`StreamName: "`, name, `",`)
		g.P("Handler: ", handlerName(s, name), ",")
		g.P("ServerStreams: true,")
		g.P("ClientStreams: true,")
		g.P("},")
	}
	g.P("},")
	g.P(`Metadata: "`, file.Desc.Path(), `",`)
	g.P("}")
	g.P()
}

func genClientMethod(g *protogen.GeneratedFile, s *protogen.Service, m *protogen.Method, streamIndex int) {
	receiver := "c *" + unexport(s.GoName+"Client")
	if m.Desc.Options().(*descriptorpb.MethodOptions).GetDeprecated() {
		g.P(deprecationComment)
	}
	g.P("func (", receiver, ") ", clientSignature(g, m), " {")
	if isUnary(m) {
		g.P("out := new(", g.QualifiedGoIdent(m.Output.GoIdent), ")")
		g.P("if err := c.cc.Invoke(ctx, ", fullMethodName(s, m), ", in, out, opts...); err != nil {")
		g.P("return nil, err")
		g.P("}")
		g.P("return out, nil")
		g.P("}")
		g.P()
		return
	}
	g.P("stream, err := c.cc.NewStream(ctx, &", s.GoName, "_ServiceDesc.Streams[", streamIndex, "], ", fullMethodName(s, m), ", opts...)")
	g.P("if err != nil {")
	g.P("return nil, err")
	g.P("}")
	g.P("return &", rpcPackage.Ident("GenericClientStream"), "[", typeArgs(g, m), "]{ClientStream: stream}, nil")
	g.P("}")
	g.P()
	g.P("// ", s.GoName, "_", m.GoName, "Client is the client stream of ", s.GoName, ".", m.GoName, ",")
	g.P("// named as in code generated by protoc-gen-go-grpc.")
	g.P("type ", s.GoName, "_", m.GoName, "Client = ", rpcPackage.Ident("BidiStreamingClient"), "[", typeArgs(g, m), "]")
	g.P()
}

func genUnaryHandler(g *protogen.GeneratedFile, s *protogen.Service, m *protogen.Method) {
	serverName := s.GoName + "Server"
	in := g.QualifiedGoIdent(m.Input.GoIdent)
	g.P("func ", handlerName(s, m.GoName), "(srv any, ctx ", contextPackage.Ident("Context"), ", dec func(any) error, interceptor ",
		rpcPackage.Ident("UnaryServerInterceptor"), ") (any, error) {")
	g.P("in := new(", in, ")")
	g.P("if err := dec(in); err != nil {")
	g.P("return nil, err")
	g.P("}")
	g.P("if interceptor == nil {")
	g.P("return srv.(", serverName, ").", m.GoName, "(ctx, in)")
	g.P("}")
	g.P("info := &", rpcPackage.Ident("UnaryServerInfo"), "{")
	g.P("Server: srv,")
	g.P("FullMethod: ", fullMethodName(s, m), ",")
	g.P("}")
	g.P("handler := func(ctx ", contextPackage.Ident("Context"), ", req any) (any, error) {")
	g.P("return srv.(", serverName, ").", m.GoName, "(ctx, req.(*", in, "))")
	g.P("}")
	g.P("return interceptor(ctx, in, info, handler)")
	g.P("}")
	g.P()
}

func genBidiHandler(g *protogen.GeneratedFile, s *protogen.Service, m *protogen.Method) {
	g.P("func ", handlerName(s, m.GoName), "(srv any, stream ", rpcPackage.Ident("ServerStream"), ") error {")
	g.P("return srv.(", s.GoName, "Server).", m.GoName, "(&", rpcPackage.Ident("GenericServerStream"), "[", typeArgs(g, m), "]{ServerStream: stream})")
	g.P("}")
	g.P()
	g.P("// ", s.GoName, "_", m.GoName, "Server is the server stream of ", s.GoName, ".", m.GoName, ",")
	g.P("// named as in code generated by protoc-gen-go-grpc.")
	g.P("type ", s.GoName, "_", m.GoName, "Server = ", rpcPackage.Ident("BidiStreamingServer"), "[", typeArgs(g, m), "]")
	g.P()
}

func clientSignature(g *protogen.GeneratedFile, m *protogen.Method) string {
	ctx := g.QualifiedGoIdent(contextPackage.Ident("Context"))
	opts := g.QualifiedGoIdent(rpcPackage.Ident("CallOption"))
	if isUnary(m) {
		return fmt.Sprintf("%s(ctx %s, in *%s, opts ...%s) (*%s, error)",
			m.GoName, ctx, g.QualifiedGoIdent(m.Input.GoIdent), opts, g.QualifiedGoIdent(m.Output.GoIdent))
	}
	return fmt.Sprintf("%s(ctx %s, opts ...%s) (%s[%s], error)",
		m.GoName, ctx, opts, g.QualifiedGoIdent(rpcPackage.Ident("BidiStreamingClient")), typeArgs(g, m))
}

func serverSignature(g *protogen.GeneratedFile, m *protogen.Method) string {
	if isUnary(m) {
		return fmt.Sprintf("%s(%s, *%s) (*%s, error)", m.GoName, g.QualifiedGoIdent(contextPackage.Ident("Context")),
			g.QualifiedGoIdent(m.Input.GoIdent), g.QualifiedGoIdent(m.Output.GoIdent))
	}
	return fmt.Sprintf("%s(%s[%s]) error", m.GoName, g.QualifiedGoIdent(rpcPackage.Ident("BidiStreamingServer")), typeArgs(g, m))
}

func typeArgs(g *protogen.GeneratedFile, m *protogen.Method) string {
	return g.QualifiedGoIdent(m.Input.GoIdent) + ", " + g.QualifiedGoIdent(m.Output.GoIdent)
}

func genServiceComments(g *protogen.GeneratedFile, s *protogen.Service, deprecated bool) {
	if s.Comments.Leading != "" {
		g.P("//")
		g.P(strings.TrimSpace(s.Comments.Leading.String()))
	}
	if deprecated {
		g.P("//")
		g.P(deprecationComment)
	}
}

func genMethodComments(g *protogen.GeneratedFile, m *protogen.Method) {
	deprecated := m.Desc.Options().(*descriptorpb.MethodOptions).GetDeprecated()
	if m.Comments.Leading != "" {
		g.P(strings.TrimSpace(m.Comments.Leading.String()))
		if deprecated {
			g.P("//")
		}
	}
	if deprecated {
		g.P(deprecationComment)
	}
}

func genLeadingComments(g *protogen.GeneratedFile, loc protoreflect.SourceLocation) {
	for _, s := range loc.LeadingDetachedComments {
		g.P(protogen.Comments(s))
		g.P()
	}
	if s := loc.LeadingComments; s != "" {
		g.P(protogen.Comments(s))
		g.P()
	}
}

func isUnary(m *protogen.Method) bool {
	return !m.Desc.IsStreamingClient() && !m.Desc.IsStreamingServer()
}

func fullMethodName(s *protogen.Service, m *protogen.Method) string {
	return s.GoName + "_" + m.GoName + "_FullMethodName"
}

func handlerName(s *protogen.Service, method string) string {
	return "_" + s.GoName + "_" + method + "_Handler"
}

func unexport(s string) string { return strings.ToLower(s[:1]) + s[1:] }
